/**
 * Get the Cloudinary URL for any local path or key.
 * Falls back to local path if not in the library.
 * 
 * @param {string} path - Local path like "/images/flag-logo.avif"
 * @returns {string} - Fast Cloudinary CDN URL
 */
export function getCdnLink(path) {
  if (!path) return '';
  if (path.startsWith('http://') || path.startsWith('https://')) return path;
  const normalized = path.startsWith('/') ? path : `/${path}`;
  return CDN_URLS[normalized] || normalized;
}

